#!/usr/bin/env node
// ---------------------------------------------------------------------------
// gen-codex-probe.mjs
//
// Generates a throwaway plugin that calls farever.player.codex(id) against
// every known collectible id and logs the hits.
//
// The question it answers: is the codex reader bestiary-only, or is it a
// general account-collection lookup? The bytecode carries a whole codex tree
// (data.CodexNode, ProgressCalcMode, ui.win.codex.CodexUnitSheet AND
// CodexActivitySheet) and the API returns a "codex tree path" per entry - so
// if mounts / gliders / appearances are nodes in that tree, this reads real
// account-wide ownership instead of observing items as they pass by.
//
// Plugins are sandboxed with no file access and no require(), so the id list
// has to be baked into the generated .lua.
//
// Usage:  node tools/gen-codex-probe.mjs   (needs tools/out/classified.json)
// Output: tools/out/codex_probe.lua
// ---------------------------------------------------------------------------

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'out');
const SRC = join(OUT, 'classified.json');

if (!existsSync(SRC)) {
  console.error('missing tools/out/classified.json - run: node tools/scan-hlboot.mjs');
  process.exit(1);
}

const buckets = JSON.parse(readFileSync(SRC, 'utf8'));

// Cap per bucket: the probe runs on the render thread, so keep the total
// bounded. Enough breadth to prove or kill the hypothesis.
const PLAN = [
  ['mount', buckets.mounts, 63],
  ['glider', buckets.gliders, 70],
  ['armor', buckets.armor, 120],
  ['weapon', buckets.weapons, 40],
  ['companion', (buckets.other || []).filter((s) => /^Sprout_[A-Z]/.test(s)), 40],
  ['chest', buckets.chests, 30],
  ['recipe', buckets.recipes, 30],
  ['monster', buckets.monsters, 20], // control: these SHOULD hit
];

// Ids confirmed owned on this account from a live equipment dump. If the
// codex reader covers appearances at all, these are the ones that must hit.
const KNOWN_OWNED = [
  'Head_RDemon_Craft_WizCle', 'Shoulders_RDemon_AssWiz', 'Chest_RCrimson_Wiz',
  'Back_RCrimson_WizCle', 'Hands_RDemon_WizCle', 'Waist_RCrimson_WizCle',
  'Legs_RDemon_Wiz', 'Feet_RDemon_WizCle', 'Necklace_Z2RCraft',
  'Finger_Z3RCraft_Cri', 'Trinket_Crimson', 'Staff_Censer', 'Staff_SummonDemon',
  'Mount_Crab_Demonic', 'Glider_Bat_Demon',
];

const groups = [];
let total = 0;
for (const [name, list, cap] of PLAN) {
  const ids = (list || []).slice(0, cap);
  if (!ids.length) continue;
  total += ids.length;
  groups.push({ name, ids });
}
groups.unshift({ name: 'known_owned', ids: KNOWN_OWNED });
total += KNOWN_OWNED.length;

const luaGroups = groups
  .map(
    (g) =>
      `  { name = ${JSON.stringify(g.name)}, ids = {\n` +
      g.ids.map((i) => `    ${JSON.stringify(i)},`).join('\n') +
      `\n  } },`
  )
  .join('\n');

const lua = `-- GENERATED by tools/gen-codex-probe.mjs - throwaway diagnostic plugin.
-- Calls farever.player.codex(id) on every known collectible id and logs the
-- hits, to find out whether the codex reader is bestiary-only or a general
-- account-collection lookup.
--
-- Delete this file from data/plugins when you are done.

local GROUPS = {
${luaGroups}
}

local done = false
local started = 0
local summary = "not run yet"

local function run()
  local hits, misses, lines = 0, 0, 0
  farever.log.info("codex_probe: BEGIN (${total} ids)")
  for _, g in ipairs(GROUPS) do
    local ghit = 0
    for _, id in ipairs(g.ids) do
      local ok, c = pcall(farever.player.codex, id)
      if ok and type(c) == "table" then
        ghit = ghit + 1
        hits = hits + 1
        if lines < 60 then
          lines = lines + 1
          farever.log.info(string.format(
            "codex_probe HIT [%s] %s -> state=%s completed=%s %s/%s name=%s path=%s",
            g.name, id, tostring(c.state), tostring(c.completed),
            tostring(c.progress), tostring(c.max),
            tostring(c.name), tostring(c.path)))
        end
      else
        misses = misses + 1
      end
    end
    farever.log.info(string.format("codex_probe GROUP %s: %d/%d hit",
      g.name, ghit, #g.ids))
  end
  summary = string.format("%d hits / %d misses", hits, misses)
  farever.log.info("codex_probe: END " .. summary)
end

function on_init()
  done = false
  started = 0
end

function on_render()
  imgui.text("codex probe")
  imgui.text(summary)
  if not done then
    if not farever.player.locked() then
      imgui.text("waiting for character lock...")
      return
    end
    -- let the codex finish loading before probing
    started = started + 1
    if started > 60 then
      done = true
      run()
    else
      imgui.text(string.format("probing in %d frames...", 60 - started))
    end
  end
end
`;

writeFileSync(join(OUT, 'codex_probe.lua'), lua, 'utf8');
console.log(`wrote ${join(OUT, 'codex_probe.lua')}`);
console.log(`  ${groups.length} groups, ${total} ids`);
for (const g of groups) console.log(`    ${g.name.padEnd(14)} ${g.ids.length}`);
